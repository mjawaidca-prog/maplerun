/**
 * PDF RL-1 slip (Revenu Québec) — sibling of the pay-stub PDF, following
 * the same @react-pdf/renderer pattern. All RL-1 boxes are printed with
 * their official box letters. Module coherence warnings are deliberately
 * NOT printed on the slip itself (they are shown in the web detail view).
 */

import { Document, Page, Text, View, StyleSheet } from "@react-pdf/renderer";

const styles = StyleSheet.create({
  page: { padding: 0, fontFamily: "Helvetica", fontSize: 10, lineHeight: 1.4, color: "#1C1917" },
  header: { backgroundColor: "#8F1D17", color: "#FFF", padding: "28 36", flexDirection: "row", justifyContent: "space-between" },
  headerName: { fontSize: 20, fontFamily: "Helvetica-Bold", color: "#FFF" },
  headerLabel: { fontSize: 12, fontFamily: "Helvetica-Bold", letterSpacing: 3, opacity: 0.85 },
  headerValue: { fontSize: 11, opacity: 0.9, marginTop: 2 },
  empRow: { padding: "22 36 16", borderBottom: "1 solid #E7E5E4", flexDirection: "row", justifyContent: "space-between" },
  empLabel: { fontSize: 10, color: "#A8A29E", textTransform: "uppercase", letterSpacing: 1.5 },
  empName: { fontSize: 16, fontFamily: "Helvetica-Bold", marginTop: 1 },
  empSub: { fontSize: 11, color: "#78716C" },
  grid: { padding: "20 36", flexDirection: "row", flexWrap: "wrap", gap: 10 },
  box: { width: "31%", border: "1 solid #E7E5E4", borderRadius: 8, padding: "10 12" },
  boxLetter: { fontSize: 10, fontFamily: "Helvetica-Bold", color: "#B3261E", textTransform: "uppercase", letterSpacing: 1 },
  boxLabel: { fontSize: 9, color: "#78716C", marginTop: 1 },
  boxValue: { fontSize: 14, fontFamily: "Courier-Bold", marginTop: 4, textAlign: "right" },
  footer: { padding: "14 36 28", borderTop: "1 solid #E7E5E4", flexDirection: "row", justifyContent: "space-between" },
  footerText: { fontSize: 9, color: "#A8A29E" },
});

function fmtCAD(n: number): string { return `$${n.toFixed(2)}`; }

export interface Rl1SlipPdfData {
  companyName: string;
  employeeName: string;
  year: number;
  boxes: Array<{ letter: string; label: string; value: number }>;
  caseOCode: string | null;
}

function BoxCell({ letter, label, value }: { letter: string; label: string; value: number }) {
  return (
    <View style={styles.box}>
      <Text style={styles.boxLetter}>Box {letter}</Text>
      <Text style={styles.boxLabel}>{label}</Text>
      <Text style={styles.boxValue}>{fmtCAD(value)}</Text>
    </View>
  );
}

export function Rl1SlipPdf({ data }: { data: Rl1SlipPdfData }) {
  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <View>
            <Text style={styles.headerName}>{data.companyName}</Text>
            <Text style={{ fontSize: 10, opacity: 0.7, marginTop: 2 }}>Relevé 1 · Revenu Québec</Text>
          </View>
          <View style={{ alignItems: "flex-end" }}>
            <Text style={styles.headerLabel}>RL-1 SLIP</Text>
            <Text style={styles.headerValue}>Taxation Year · {data.year}</Text>
          </View>
        </View>

        <View style={styles.empRow}>
          <View>
            <Text style={styles.empLabel}>Employee</Text>
            <Text style={styles.empName}>{data.employeeName}</Text>
            <Text style={styles.empSub}>Province of employment · QC</Text>
          </View>
          <View style={{ alignItems: "flex-end" }}>
            <Text style={styles.empLabel}>Employer</Text>
            <Text style={{ fontSize: 12, fontFamily: "Helvetica-Bold", marginTop: 1 }}>{data.companyName}</Text>
          </View>
        </View>

        <View style={styles.grid}>
          {data.boxes.map((b) => (
            <BoxCell key={b.letter} letter={b.letter} label={b.label} value={b.value} />
          ))}
          {data.caseOCode ? (
            <View style={styles.box}>
              <Text style={styles.boxLetter}>Code (case O)</Text>
              <Text style={styles.boxLabel}>Type of box O income</Text>
              <Text style={styles.boxValue}>{data.caseOCode}</Text>
            </View>
          ) : null}
        </View>

        <View style={styles.footer}>
          <Text style={styles.footerText}>Generated by Nexvar Pay · A NexvarLab product</Text>
          <Text style={styles.footerText}>For your records. Not an official Revenu Québec document.</Text>
        </View>
      </Page>
    </Document>
  );
}

